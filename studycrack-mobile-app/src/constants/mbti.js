// 답안 배열(길이 36, 값 1=a / 2=b)로 4글자 코드 산출. 섹션별 9문항에서 다수결.
export function computeMbtiCode(answers = []) {
  let code = '';
  for (let g = 0; g < 4; g += 1) {
    let countA = 0;
    let countB = 0;
    for (let i = g * 9; i < g * 9 + 9; i += 1) {
      if (answers[i] === 1) countA += 1;
      else if (answers[i] === 2) countB += 1;
    }
    code += countA >= countB ? MBTI_SECTIONS[g].pair[0] : MBTI_SECTIONS[g].pair[1];
  }
  return code;
}

export function normalizeMbtiCode(code = '') {
  const upper = String(code || '').toUpperCase().trim();
  return MBTI_TYPE_PROFILES[upper] ? upper : '';
}

export function getMbtiProfile(code = '') {
  const normalized = normalizeMbtiCode(code) || 'CSDR';
  return { code: normalized, ...MBTI_TYPE_PROFILES[normalized], subjects: MBTI_RECOMMENDED_SUBJECTS[normalized] || [] };
}

export function countMbtiAnswered(answers = []) {
  return (answers || []).filter((v) => v === 1 || v === 2).length;
}
