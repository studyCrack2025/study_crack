import assert from 'node:assert/strict';
import { analyzeCSSCollection, analyzeCSSUsage } from './css-usage-analysis.mjs';

const css = '.live, .retired { color: red; }\n.live:hover { color: blue; }\n.kind-offline { display: grid; }';
const source = 'className="live"; const kindClass = `kind-${kind}`;';
const allowlist = { 'kind-offline': 'Generated by kind-${kind}.' };
const audit = analyzeCSSUsage(css, source, allowlist);
assert.deepEqual(audit.candidates, ['retired']);
assert.deepEqual(audit.allowed, ['kind-offline']);
assert.deepEqual(audit.rules, [{ line: 1, selector: '.live, .retired', candidateSelectors: ['.retired'], retainedSelectors: ['.live'] }]);
assert.deepEqual(analyzeCSSUsage('.card {}', 'className="card-title"').candidates, ['card'], 'partial names must not hide debt');
assert.deepEqual(analyzeCSSUsage('.card {}', 'document.querySelector(".card")').candidates, [], 'DOM queries are references, not dead code');
assert.throws(() => analyzeCSSUsage(css, source, { absent: 'Removed class.' }), /stale.*class/);
assert.throws(() => analyzeCSSUsage(css, source, { 'kind-offline': '' }), /needs a reason/);
assert.throws(() => analyzeCSSUsage(css, source, { live: 'Now statically referenced.' }), /redundant/);
assert.throws(() => analyzeCSSCollection({}, source, { 'deleted.css': allowlist }), /stale.*owner/, 'deleting an entire owner must not bypass stale allowlist validation');
assert.deepEqual(Object.keys(analyzeCSSCollection({ 'current.css': css }, source, { 'current.css': allowlist })), ['current.css']);
console.log('CSS audit contracts passed: dynamic usage, DOM queries, mixed selectors and stale owner/class/reason checks.');
