import assert from 'node:assert/strict';
import { createPlannerStorageController } from '../src/features/planner/storage-controller.js';
import { hydratePlannerStorage, persistPlannerStorage, readPlannerStorage } from '../src/features/planner/storage.js';

const item = { id: 'plan-a', date: '2026-09-07', subject: '국어', content: '독서', minutes: 60 };
let raw = JSON.stringify([item]);
let blocked = false;
let unreadable = false;
let writes = 0;
const storage = {
  getItem() { if (unreadable) throw new Error('blocked'); return raw; },
  setItem(key, value) { if (blocked) throw new Error('quota'); writes++; raw = value; }
};
let state = hydratePlannerStorage(storage).plannerItems;
const controller = createPlannerStorageController({ items: state, storage, commit: items => { state = items; } });
assert.equal(writes, 0, 'mount must never rewrite storage');
blocked = true;
const before = raw;
assert.equal(controller.update(items => [...items, { ...item, id: 'plan-b' }]), false);
assert.equal(state.length, 1);
assert.equal(raw, before);
assert.equal(controller.getStatus().error, 'write');
blocked = false;
assert.equal(controller.update(items => [...items, { ...item, id: 'plan-b' }]), true);
assert.equal(state.length, 2);
controller.update(items => items.map(item => ({ ...item, done: true })));
assert.equal(state.length, 2, 'batched updates must use latest committed list');
assert.ok(state.every(item => item.done));
blocked = true;
const addMinutes = items => items.map(item => ({ ...item, doneMinutes: (item.doneMinutes || 0) + 10 }));
controller.update(addMinutes, { retainOnFailure: true });
controller.update(addMinutes, { retainOnFailure: true });
assert.equal(state[0].doneMinutes, 20);
assert.equal(controller.getStatus().pending, true);
assert.equal(controller.retry(), false);
assert.equal(state[0].doneMinutes, 20, 'failed retries must not repeat increments');
blocked = false;
assert.equal(controller.retry(), true);
assert.equal(state[0].doneMinutes, 20);
assert.equal(controller.retry(), true);
assert.equal(state[0].doneMinutes, 20, 'successful retry must clear pending mutations');
raw = JSON.stringify([{ ...item, content: '다른 화면에서 수정' }]);
assert.equal(controller.update(() => []), false);
assert.equal(controller.getStatus().error, 'conflict');
assert.equal(controller.retry(), true);
assert.equal(state[0].content, '다른 화면에서 수정');
raw = '{broken';
assert.equal(controller.update(() => []), false);
assert.equal(controller.retry(), false);
assert.equal(raw, '{broken');
assert.deepEqual(hydratePlannerStorage(storage), {});
for (const invalid of ['null', '{}', '[null]', '[{"minutes":"invalid"}]']) {
  raw = invalid;
  assert.equal(readPlannerStorage(storage).ok, false);
  assert.equal(raw, invalid);
}
raw = JSON.stringify([item]);
unreadable = true;
assert.equal(controller.update(() => []), false);
assert.equal(controller.getStatus().error, 'read');
unreadable = false;
assert.equal(controller.retry(), true);
assert.equal(state.length, 1);
assert.equal(persistPlannerStorage({}, null), false);
assert.equal(persistPlannerStorage({}, {}), false);
assert.equal(readPlannerStorage(null).ok, false);
raw = JSON.stringify([item, { ...item, id: 'external-plan' }]);
const delayed = createPlannerStorageController({ items: [item], storage, commit: items => { state = items; } });
delayed.update(items => items.map(item => ({ ...item, done: true })));
assert.equal(state.length, 2, 'a delayed screen mount must use the latest readable snapshot');
blocked = true;
delayed.update(addMinutes, { retainOnFailure: true });
raw = JSON.stringify([item, { ...item, id: 'new-external-plan' }]);
assert.equal(delayed.retry(), false);
assert.equal(state[1].id, 'new-external-plan', 'failed retry must retain the rebased pending copy');
blocked = false;
delayed.update(items => [...items, { ...item, id: 'third-plan' }]);
assert.equal(state.length, 3);
assert.equal(state[1].id, 'new-external-plan');
assert.equal(state[0].doneMinutes, 10);
console.log('planner storage recovery passed: write-before-commit, pending study copy, read/corruption/conflict guards, idempotent local retry');
